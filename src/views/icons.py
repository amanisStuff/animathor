def load_icon(name, size=20):
    """Load (and cache) a bundled icon, or None if it is missing."""
    key = (name, size)
    if key not in _img_cache:
        path = os.path.join(_ICON_DIR, f"{name}_{size}.png")
        if os.path.exists(path):
            try:
                _img_cache[key] = pygame.image.load(path).convert_alpha()
            except Exception:
                _img_cache[key] = None
        else:
            _img_cache[key] = None
    return _img_cache[key]


def _tinted(img, color):
    """Recolour a white icon while preserving its alpha mask."""
    key = (img, tuple(color))
    result = _tint_cache.get(key)
    if result is None:
        result = pygame.Surface(img.get_size(), pygame.SRCALPHA)
        result.fill(color)
        result.blit(img, (0, 0), special_flags=pygame.BLEND_RGBA_MULT)
        _tint_cache[key] = result
    return result


def _draw_fallback_icon(screen, name, center, color, size=20):
    """Draw a simple procedural icon when a PNG asset is unavailable."""
    cx, cy = int(center[0]), int(center[1])
    s = max(12, int(size))
    c = color
    w = max(2, s // 10)

    if name == "flip_h":
        # vertical axis with arrows left/right
        pygame.draw.line(screen, c, (cx, cy - s // 2 + 2), (cx, cy + s // 2 - 2), w)
        y = cy
        for dx, sign in ((-1, -1), (1, 1)):
            tip = (cx + sign * (s // 2 - 2), y)
            base_x = cx + sign * (s // 5)
            pygame.draw.polygon(screen, c, [tip, (base_x, y - 4), (base_x, y + 4)])
        return True
    if name == "flip_v":
        # horizontal axis with arrows up/down
        pygame.draw.line(screen, c, (cx - s // 2 + 2, cy), (cx + s // 2 - 2, cy), w)
        x = cx
        for dy, sign in ((-1, -1), (1, 1)):
            tip = (x, cy + sign * (s // 2 - 2))
            base_y = cy + sign * (s // 5)
            pygame.draw.polygon(screen, c, [tip, (x - 4, base_y), (x + 4, base_y)])
        return True

    # alignment icons: reference line + two rectangles
    if name in ("align_left", "align_hcenter", "align_right", "align_top", "align_vmiddle", "align_bottom"):
        l = cx - s // 2 + 2
        r = cx + s // 2 - 2
        t = cy - s // 2 + 2
        b = cy + s // 2 - 2
        if name == "align_left":
            x = l
            pygame.draw.line(screen, c, (x, t), (x, b), w)
            pygame.draw.rect(screen, c, (x + 3, cy - 6, 9, 4), 1)
            pygame.draw.rect(screen, c, (x + 3, cy + 2, 6, 4), 1)
        elif name == "align_hcenter":
            x = cx
            pygame.draw.line(screen, c, (x, t), (x, b), w)
            pygame.draw.rect(screen, c, (cx - 5, cy - 6, 10, 4), 1)
            pygame.draw.rect(screen, c, (cx - 3, cy + 2, 6, 4), 1)
        elif name == "align_right":
            x = r
            pygame.draw.line(screen, c, (x, t), (x, b), w)
            pygame.draw.rect(screen, c, (x - 12, cy - 6, 9, 4), 1)
            pygame.draw.rect(screen, c, (x - 9, cy + 2, 6, 4), 1)
        elif name == "align_top":
            y = t
            pygame.draw.line(screen, c, (l, y), (r, y), w)
            pygame.draw.rect(screen, c, (cx - 7, y + 3, 4, 9), 1)
            pygame.draw.rect(screen, c, (cx + 2, y + 3, 4, 6), 1)
        elif name == "align_vmiddle":
            y = cy
            pygame.draw.line(screen, c, (l, y), (r, y), w)
            pygame.draw.rect(screen, c, (cx - 7, cy - 5, 4, 10), 1)
            pygame.draw.rect(screen, c, (cx + 2, cy - 3, 4, 6), 1)
        elif name == "align_bottom":
            y = b
            pygame.draw.line(screen, c, (l, y), (r, y), w)
            pygame.draw.rect(screen, c, (cx - 7, y - 12, 4, 9), 1)
            pygame.draw.rect(screen, c, (cx + 2, y - 9, 4, 6), 1)
        return True

    # Polygon / star shape icons.
    if name in ("shape_polygon", "shape_star"):
        import math as _math
        n = 6 if name == "shape_polygon" else 5
        rad = max(6, s // 2 - 2)
        pts = []
        for i in range(n * (2 if name == "shape_star" else 1)):
            a = -_math.pi / 2 + _math.pi * i / n
            r = rad if (name == "shape_polygon" or i % 2 == 0) else rad * 0.45
            pts.append((cx + r * _math.cos(a), cy + r * _math.sin(a)))
        pygame.draw.polygon(screen, c, pts, 1)
        return True

    # Boolean icons: two overlapping shapes with an operation marker.
    if name in ("subtract", "exclude", "union", "intersect"):
        r1 = (cx - s // 2 + 2, cy - s // 4, s // 2 + 4, s // 2 - 1)
        r2 = (cx - 3, cy - s // 4, s // 2 + 4, s // 2 - 1)
        if name == "union":
            pygame.draw.rect(screen, c, r1, 1)
            pygame.draw.rect(screen, c, r2, 1)
        elif name == "intersect":
            ix = max(r1[0], r2[0])
            iy = max(r1[1], r2[1])
            rx = min(r1[0] + r1[2], r2[0] + r2[2])
            by = min(r1[1] + r1[3], r2[1] + r2[3])
            if rx > ix and by > iy:
                pygame.draw.rect(screen, c, (ix, iy, rx - ix, by - iy))
        else:
            pygame.draw.rect(screen, c, r1, 1)
            pygame.draw.rect(screen, c, r2, 1)
            pygame.draw.line(screen, c, (cx - 3, cy), (cx + 3, cy), w)
            if name == "exclude":
                pygame.draw.line(screen, c, (cx, cy - 3), (cx, cy + 3), w)
        return True

    # Last resort for an unknown name or a missing/corrupt PNG: draw a neutral
    # glyph instead of leaving the button blank.
    pygame.draw.circle(screen, c, (cx, cy), max(3, s // 3), w)
    pygame.draw.circle(screen, c, (cx, cy), max(1, w // 2))
    return True


def draw_icon(screen, name, rect, color=None, size=20, enabled=True):
    """Draw a bundled icon centred in ``rect`` (or at a position tuple)."""
    img = load_icon(name, size)
    c = TEXT_DISABLED if not enabled else (color if color is not None else SURFACE)
    if img is None:
        if isinstance(rect, pygame.Rect):
            center = rect.center
        else:
            center = rect
        _draw_fallback_icon(screen, name, center, c, size=size)
        return
    if not enabled:
        img = _tinted(img, TEXT_DISABLED)
    elif color is not None:
        img = _tinted(img, color)
    if isinstance(rect, pygame.Rect):
        pos = img.get_rect(center=rect.center).topleft
    else:
        pos = img.get_rect(center=rect).topleft
    screen.blit(img, pos)


def draw_tooltip(screen, mouse_pos, text, font=None):
    """Render a name/shortcut tooltip near the cursor, clamped to the screen."""
    if not text:
        return
    if font is None:
        font = pygame.font.SysFont(None, FONT_SIZE_TOOLTIP)
    label = font.render(text, True, TOOLTIP_TEXT)
    pad_x, pad_y = 9, 6
    r = label.get_rect()
    r.width += pad_x * 2
    r.height += pad_y * 2
    r.topleft = (mouse_pos[0] + 16, mouse_pos[1] + 18)
    sw, sh = screen.get_size()
    r.right = min(r.right, sw - 4)
    r.bottom = min(r.bottom, sh - 4)
    pygame.draw.rect(screen, TOOLTIP_BG, r, border_radius=RADIUS_SM)
    pygame.draw.rect(screen, TOOLTIP_BORDER, r, BORDER_WIDTH, border_radius=RADIUS_SM)
    screen.blit(label, (r.x + pad_x, r.y + pad_y))
