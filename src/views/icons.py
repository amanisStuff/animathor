def load_icon(name, size=20):
    """Load (and cache) a bundled icon, or None if it is missing."""
    key = (name, size)
    if key not in _img_cache:
        path = os.path.join(_ICON_DIR, f"{name}_{size}.png")
        if os.path.exists(path):
            try:
                _img_cache[key] = pygame.image.load(path).convert_alpha()
            except Exception:
                _img_cache[key] = None
        else:
            _img_cache[key] = None
    return _img_cache[key]


def _tinted(img, color):
    """Recolour a white icon while preserving its alpha mask."""
    key = (img, tuple(color))
    result = _tint_cache.get(key)
    if result is None:
        result = pygame.Surface(img.get_size(), pygame.SRCALPHA)
        result.fill(color)
        result.blit(img, (0, 0), special_flags=pygame.BLEND_RGBA_MULT)
        _tint_cache[key] = result
    return result


def draw_icon(screen, name, rect, color=None, size=20, enabled=True):
    """Draw a bundled icon centred in ``rect`` (or at a position tuple)."""
    img = load_icon(name, size)
    if img is None:
        return
    if not enabled:
        img = _tinted(img, (170, 176, 184))
    elif color is not None:
        img = _tinted(img, color)
    if isinstance(rect, pygame.Rect):
        pos = img.get_rect(center=rect.center).topleft
    else:
        pos = img.get_rect(center=rect).topleft
    screen.blit(img, pos)


def draw_tooltip(screen, mouse_pos, text, font=None):
    """Render a name/shortcut tooltip near the cursor, clamped to the screen."""
    if not text:
        return
    if font is None:
        font = pygame.font.SysFont(None, 19)
    label = font.render(text, True, (240, 244, 250))
    pad_x, pad_y = 9, 6
    r = label.get_rect()
    r.width += pad_x * 2
    r.height += pad_y * 2
    r.topleft = (mouse_pos[0] + 16, mouse_pos[1] + 18)
    sw, sh = screen.get_size()
    r.right = min(r.right, sw - 4)
    r.bottom = min(r.bottom, sh - 4)
    pygame.draw.rect(screen, (28, 32, 40), r, border_radius=5)
    pygame.draw.rect(screen, (96, 104, 120), r, 1, border_radius=5)
    screen.blit(label, (r.x + pad_x, r.y + pad_y))
